/**
 * Realistic Indian Meme Dialogue Sticker Generator with die-cut vinyl finish,
 * authentic Bollywood poster colors, custom character badges and speech balloons.
 */
export const createRealisticDesiSticker = ({
  character,
  dialogue,
  hindiDialogue = "",
  movie = "",
  theme = "gold", // "gold" | "red" | "emerald" | "purple" | "cyan" | "orange" | "dark" | "pink"
  badgeIcon = "🔥",
  badgeBg = "#f59e0b",
  dialogueColor = "#ffffff",
}) => {
  const themes = {
    gold: { bg1: "#b45309", bg2: "#f59e0b", border: "#fef08a", ribbon: "#78350f" },
    red: { bg1: "#991b1b", bg2: "#ef4444", border: "#fecaca", ribbon: "#450a0a" },
    emerald: { bg1: "#065f46", bg2: "#10b981", border: "#a7f3d0", ribbon: "#022c22" },
    purple: { bg1: "#581c87", bg2: "#a855f7", border: "#e9d5ff", ribbon: "#2e1065" },
    cyan: { bg1: "#155e75", bg2: "#06b6d4", border: "#cffafe", ribbon: "#083344" },
    orange: { bg1: "#9a3412", bg2: "#f97316", border: "#ffedd5", ribbon: "#431407" },
    dark: { bg1: "#09090b", bg2: "#27272a", border: "#e4e4e7", ribbon: "#000000" },
    pink: { bg1: "#9d174d", bg2: "#ec4899", border: "#fbcfe8", ribbon: "#500724" },
  };

  const currentTheme = themes[theme] || themes.gold;
  const safeChar = (character || "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  const safeDialogue = (dialogue || "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  const safeHindi = (hindiDialogue || "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  const safeMovie = (movie || "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

  const svg = `
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512" shape-rendering="geometricPrecision" text-rendering="geometricPrecision">
  <defs>
    <!-- HD Background Gradient -->
    <linearGradient id="mainGrad" x1="0%" y1="0%" x2="100%" y2="100%">
      <stop offset="0%" stop-color="${currentTheme.bg1}" />
      <stop offset="100%" stop-color="${currentTheme.bg2}" />
    </linearGradient>

    <!-- Gloss Highlight -->
    <linearGradient id="glossGrad" x1="0%" y1="0%" x2="0%" y2="100%">
      <stop offset="0%" stop-color="#ffffff" stop-opacity="0.4" />
      <stop offset="100%" stop-color="#ffffff" stop-opacity="0" />
    </linearGradient>

    <!-- Deep Die-Cut Vinyl Shadow -->
    <filter id="realisticStickerShadow" x="-20%" y="-20%" width="140%" height="140%">
      <feDropShadow dx="0" dy="16" stdDeviation="12" flood-color="#000000" flood-opacity="0.5"/>
      <feDropShadow dx="0" dy="4" stdDeviation="4" flood-color="#000000" flood-opacity="0.3"/>
    </filter>

    <!-- 3D Text Drop Shadow -->
    <filter id="textShadow">
      <feDropShadow dx="3" dy="3" stdDeviation="1" flood-color="#000000" flood-opacity="0.85"/>
    </filter>
  </defs>

  <!-- 1. Outer Die-Cut Thick White Sticker Border -->
  <rect x="20" y="20" width="472" height="472" rx="80" fill="#ffffff" filter="url(#realisticStickerShadow)" stroke="#e2e8f0" stroke-width="4"/>

  <!-- 2. Main Sticker Graphic Card Surface -->
  <rect x="32" y="32" width="448" height="448" rx="68" fill="url(#mainGrad)"/>

  <!-- 3. Vinyl Gloss Highlight Overlay -->
  <path d="M 32 100 C 32 60 60 32 100 32 L 412 32 C 452 32 480 60 480 100 L 480 220 Q 256 300 32 220 Z" fill="url(#glossGrad)"/>

  <!-- 4. Top Character Avatar Circle Badge -->
  <g transform="translate(256, 136)">
    <circle cx="0" cy="0" r="70" fill="#ffffff" stroke="${currentTheme.border}" stroke-width="6" filter="url(#textShadow)"/>
    <circle cx="0" cy="0" r="58" fill="${badgeBg}" />
    <text x="0" y="16" font-size="68" text-anchor="middle" dominant-baseline="middle" font-family="'Apple Color Emoji', 'Segoe UI Emoji', sans-serif">
      ${badgeIcon}
    </text>
  </g>

  <!-- 5. Character Name Banner Ribbon -->
  <g transform="translate(256, 236)">
    <rect x="-180" y="-22" width="360" height="44" rx="22" fill="${currentTheme.ribbon}" stroke="#ffffff" stroke-width="2.5" filter="url(#textShadow)"/>
    <text x="0" y="2" font-size="20" font-weight="900" text-anchor="middle" dominant-baseline="middle" fill="#fef08a" font-family="'Impact', 'Outfit', system-ui, sans-serif" letter-spacing="1.5px" text-transform="uppercase">
      ★ ${safeChar} ★
    </text>
  </g>

  <!-- 6. Big Realistic Dialogue Text (Double Stroked Bollywood Poster Font) -->
  <g transform="translate(256, 320)">
    <!-- Black Outline -->
    <text x="0" y="0" font-size="36" font-weight="900" text-anchor="middle" dominant-baseline="middle" fill="#000000" stroke="#000000" stroke-width="10" stroke-linejoin="round" font-family="'Impact', 'Outfit', system-ui, sans-serif" letter-spacing="-0.5px">
      "${safeDialogue}"
    </text>
    <!-- Foreground Bright Text -->
    <text x="0" y="0" font-size="36" font-weight="900" text-anchor="middle" dominant-baseline="middle" fill="${dialogueColor}" font-family="'Impact', 'Outfit', system-ui, sans-serif" letter-spacing="-0.5px">
      "${safeDialogue}"
    </text>
  </g>

  <!-- 7. Hindi Punchline Text / Subtitle (if available) -->
  ${
    safeHindi
      ? `<text x="256" y="380" font-size="22" font-weight="900" text-anchor="middle" dominant-baseline="middle" fill="#ffffff" opacity="0.95" font-family="system-ui, sans-serif" filter="url(#textShadow)">
          ${safeHindi}
        </text>`
      : ""
  }

  <!-- 8. Bottom Movie / Origin Badge Capsule -->
  <g transform="translate(256, 436)">
    <rect x="-110" y="-16" width="220" height="32" rx="16" fill="#000000" opacity="0.55"/>
    <text x="0" y="2" font-size="15" font-weight="800" text-anchor="middle" dominant-baseline="middle" fill="#ffffff" letter-spacing="1.5px" font-family="system-ui, sans-serif">
      ${safeMovie ? safeMovie.toUpperCase() : "DESI MEME"}
    </text>
  </g>
</svg>
`.trim();

  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
};

