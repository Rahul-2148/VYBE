/**
 * Storage Helpers for Recents and Custom Stickers
 */
const RECENT_STICKERS_KEY = "vybe_recent_stickers";
const CUSTOM_STICKERS_KEY = "vybe_custom_stickers";

export const getRecentStickers = () => {
  try {
    const raw = localStorage.getItem(RECENT_STICKERS_KEY);
    return raw ? JSON.parse(raw) : [];
  } catch {
    return [];
  }
};

export const addRecentSticker = (sticker) => {
  try {
    const current = getRecentStickers().filter((s) => s.id !== sticker.id);
    const updated = [sticker, ...current].slice(0, 24);
    localStorage.setItem(RECENT_STICKERS_KEY, JSON.stringify(updated));
    return updated;
  } catch {
    return [];
  }
};

export const getCustomStickers = () => {
  try {
    const raw = localStorage.getItem(CUSTOM_STICKERS_KEY);
    return raw ? JSON.parse(raw) : [];
  } catch {
    return [];
  }
};

export const saveCustomSticker = (customSticker) => {
  try {
    const current = getCustomStickers().filter((s) => s.id !== customSticker.id);
    const updated = [customSticker, ...current];
    localStorage.setItem(CUSTOM_STICKERS_KEY, JSON.stringify(updated));
    return updated;
  } catch {
    return [];
  }
};

export const deleteCustomSticker = (id) => {
  try {
    const current = getCustomStickers().filter((s) => s.id !== id);
    localStorage.setItem(CUSTOM_STICKERS_KEY, JSON.stringify(current));
    return current;
  } catch {
    return [];
  }
};
